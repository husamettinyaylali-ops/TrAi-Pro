const dict: Record<Lang, Dict> = { tr, en };
const LANG_KEY = "traipro:lang";

const Ctx = createContext<{
  lang: Lang;
  t: Dict;
  setLang: (l: Lang) => void;
  locale: string;
} | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("tr");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === "tr" || saved === "en") setLangState(saved);
    } catch {
      /* depolama kapalıysa varsayılan dil kalır */
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* yoksay */
    }
  };

  return (
    <Ctx.Provider
      value={{ lang, t: dict[lang], setLang, locale: lang === "tr" ? "tr-TR" : "en-US" }}
    >
      {children}
    </Ctx.Provider>
  );
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n outside provider");
  return c;
}

export function useFormat() {
  const { locale } = useI18n();
  return {
    num: (n: number) => new Intl.NumberFormat(locale).format(n),
    usd: (n: number) =>
      new Intl.NumberFormat(locale, { style: "currency", currency: "USD" }).format(n),
    date: (iso: string) =>
      new Intl.DateTimeFormat(locale, { dateStyle: "medium" }).format(new Date(iso)),
    dateTime: (iso: string) =>
      new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(
        new Date(iso),
      ),
    time: (iso: string) =>
      new Intl.DateTimeFormat(locale, { timeStyle: "short" }).format(new Date(iso)),
    /** Dil adı (ISO 639 kodundan, ör. "tur" → "Türkçe"); tanınmazsa kodun kendisi. */
    language: (code: string) => {
      try {
        return new Intl.DisplayNames([locale], { type: "language" }).of(code) ?? code;
      } catch {
        return code;
      }
    },
    /** Dosya boyutu: KB ya da MB, bir ondalıkla. */
    bytes: (n: number) =>
      n < 1024 * 1024
        ? `${new Intl.NumberFormat(locale, { maximumFractionDigits: 0 }).format(Math.max(1, n / 1024))} KB`
        : `${new Intl.NumberFormat(locale, { maximumFractionDigits: 1 }).format(n / 1024 / 1024)} MB`,
  };
}
